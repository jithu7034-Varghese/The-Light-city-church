// Writes docs/stock-images-to-review.md: the devotionals whose old-site image came from GoDaddy's
// stock library. Reads only the committed seed files, so it needs no database access.
//
//   npx tsx supabase/seed/write-stock-report.ts
import fs from "node:fs";
import path from "node:path";
import { legacySlugOf, normalizeSlug, stockDevotionals, type OldImageSource } from "./old-images-lib";

const root = path.resolve(import.meta.dirname, "../..");
const posts = JSON.parse(fs.readFileSync(path.join(root, "supabase/seed/posts.json"), "utf8")) as { slug: string; title: string; legacy_url?: string | null }[];
const src = JSON.parse(fs.readFileSync(path.join(root, "supabase/seed/raw/old-site-images.json"), "utf8")) as OldImageSource;

const bySlug = new Map(posts.map((p) => [p.slug, p]));
const byLegacy = new Map(posts.map((p) => [normalizeSlug(legacySlugOf(p.legacy_url) ?? ""), p.slug]));
const stock = stockDevotionals(src, (l) => byLegacy.get(normalizeSlug(l))).sort((a, b) =>
  (bySlug.get(a.slug)?.title ?? a.slug).localeCompare(bySlug.get(b.slug)?.title ?? b.slug, "en-GB"),
);
const uniqueImages = new Set(stock.map((s) => s.source)).size;
const escape = (s: string) => s.replace(/\|/g, "\\|");

const lines = [
  "# Devotional images to review (GoDaddy stock library)",
  "",
  `On the old website, **${stock.length} devotionals** used pictures from GoDaddy's built-in stock library (${uniqueImages} different pictures). GoDaddy's stock images may only be licensed for use on websites hosted with GoDaddy, so they are **not shown on the new website** until the church confirms it may use them.`,
  "",
  "What happens now:",
  "",
  "- These devotionals have **no featured image**, so the website shows its default image on the devotional cards.",
  "- The pictures were copied into the media library, unused, with the title \"GoDaddy stock image: licence not confirmed\". Please don't choose them for other content.",
  "",
  "## What the church needs to decide",
  "",
  "For each devotional, either:",
  "",
  "1. **Choose a replacement picture:** in the admin, open **Devotionals**, find the devotional, click **Choose image** under *Featured image*, upload or pick a church photo (alt text is required), then **Update published devotional**. Or",
  "2. **Confirm the licence** for the stock pictures (for example in writing from GoDaddy). Once confirmed, a developer can put them all back with `npx tsx supabase/seed/import-old-images.ts --include-stock`, or staff can pick them in the admin one by one.",
  "",
  "Leaving a devotional without a featured image is also fine.",
  "",
  `## The ${stock.length} devotionals`,
  "",
  "| # | Title | Slug (address on the new site) | Old stock picture |",
  "|---|---|---|---|",
  ...stock.map((s, i) => {
    const title = bySlug.get(s.slug)?.title ?? s.slug;
    const stockId = s.source.split("/isteam/stock/")[1] ?? s.source;
    return `| ${i + 1} | ${escape(title)} | [\`${s.slug}\`](https://thelightcitychurch.org/devotionals/${s.slug}) | [stock ${escape(stockId)}](${s.source}) |`;
  }),
  "",
  "_Generated by `npx tsx supabase/seed/write-stock-report.ts` from the old-site image list._",
  "",
];

const out = path.join(root, "docs/stock-images-to-review.md");
fs.writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${path.relative(root, out)}: ${stock.length} devotionals, ${uniqueImages} stock pictures`);
