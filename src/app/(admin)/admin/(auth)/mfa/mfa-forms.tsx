"use client";
// TOTP enrol + challenge run in the browser (the Supabase browser client updates the
// session cookie to aal2), then the server is told so it can write the activity log.
import { useEffect, useRef, useState } from "react";
import { useRouter } from "next/navigation";
import { Alert, Button, Field, Input, Skeleton } from "@/components/admin/ui";
import { createSupabaseBrowserClient } from "@/lib/supabase/client";
import { recordMfaEvent } from "../actions";

const CODE_PATTERN = /^\d{6}$/;

function useFinish(next: string) {
  const router = useRouter();
  return async (kind: "enrolled" | "verified") => {
    await recordMfaEvent(kind);
    router.replace(next);
    router.refresh();
  };
}

function CodeForm({ onSubmit, submitLabel }: { onSubmit: (code: string) => Promise<string | null>; submitLabel: string }) {
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  async function handle(e: React.FormEvent) {
    e.preventDefault();
    const clean = code.replace(/\s/g, "");
    if (!CODE_PATTERN.test(clean)) {
      setError("Enter the 6-digit code from your app.");
      return;
    }
    setBusy(true);
    setError(null);
    const err = await onSubmit(clean);
    if (err) {
      setError(err);
      setBusy(false);
      setCode("");
    }
  }

  return (
    <form onSubmit={handle} className="space-y-4" noValidate>
      <Field label="6-digit code" error={error ?? undefined}>
        <Input
          value={code}
          onChange={(e) => setCode(e.target.value)}
          inputMode="numeric"
          autoComplete="one-time-code"
          pattern="\d{6}"
          maxLength={7}
          className="text-center font-mono text-lg tracking-[0.4em]"
          autoFocus
          required
        />
      </Field>
      <Button type="submit" className="w-full" loading={busy}>{submitLabel}</Button>
    </form>
  );
}

export function MfaChallenge({ next }: { next: string }) {
  const finish = useFinish(next);
  return (
    <CodeForm
      submitLabel="Verify"
      onSubmit={async (code) => {
        const supabase = createSupabaseBrowserClient();
        const { data: factors, error } = await supabase.auth.mfa.listFactors();
        const factor = factors?.totp[0];
        if (error || !factor) return "We couldn't find your authenticator. Ask an administrator to reset your 2FA.";
        const { error: verifyError } = await supabase.auth.mfa.challengeAndVerify({ factorId: factor.id, code });
        if (verifyError) return "That code didn't work. Codes change every 30 seconds, so try the latest one.";
        await finish("verified");
        return null;
      }}
    />
  );
}

type Enrolment = { factorId: string; qrCode: string; secret: string };

export function MfaEnroll({ next }: { next: string }) {
  const finish = useFinish(next);
  const [enrolment, setEnrolment] = useState<Enrolment | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [showSecret, setShowSecret] = useState(false);
  const started = useRef(false);

  useEffect(() => {
    if (started.current) return; // StrictMode runs effects twice in dev
    started.current = true;
    (async () => {
      const supabase = createSupabaseBrowserClient();
      // Remove a half-finished enrolment from an earlier visit, or enrol() rejects the duplicate.
      const { data: existing } = await supabase.auth.mfa.listFactors();
      for (const f of existing?.all ?? []) {
        if (f.factor_type === "totp" && f.status === "unverified") {
          await supabase.auth.mfa.unenroll({ factorId: f.id });
        }
      }
      const { data, error } = await supabase.auth.mfa.enroll({
        factorType: "totp",
        friendlyName: `Authenticator ${new Date().toISOString().slice(0, 10)}`,
        issuer: "The Light City Church",
      });
      if (error || !data) {
        setError("We couldn't start 2FA setup. Refresh the page to try again.");
        return;
      }
      setEnrolment({ factorId: data.id, qrCode: data.totp.qr_code, secret: data.totp.secret });
    })();
  }, []);

  if (error) return <Alert tone="danger">{error}</Alert>;

  return (
    <div className="space-y-5">
      <div className="flex flex-col items-center gap-3">
        {enrolment ? (
          // qr_code is an SVG data URL generated by Supabase; next/image isn't needed for it.
          // eslint-disable-next-line @next/next/no-img-element
          <img src={enrolment.qrCode} alt="QR code to scan with your authenticator app" className="size-44 rounded-lg bg-white p-2" />
        ) : (
          <Skeleton className="size-44" />
        )}
        <button type="button" onClick={() => setShowSecret((s) => !s)} className="text-xs font-medium text-primary hover:underline">
          {showSecret ? "Hide setup key" : "Can't scan? Enter a setup key instead"}
        </button>
        {showSecret && enrolment && (
          <code className="break-all rounded-md bg-subtle px-3 py-2 text-center font-mono text-xs select-all">{enrolment.secret}</code>
        )}
      </div>
      <CodeForm
        submitLabel="Turn on 2FA"
        onSubmit={async (code) => {
          if (!enrolment) return "Still loading, please wait a moment.";
          const supabase = createSupabaseBrowserClient();
          const { error } = await supabase.auth.mfa.challengeAndVerify({ factorId: enrolment.factorId, code });
          if (error) return "That code didn't work. Check your phone's time is set automatically and try the latest code.";
          await finish("enrolled");
          return null;
        }}
      />
    </div>
  );
}
